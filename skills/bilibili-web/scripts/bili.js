function ensureHome() {
  fs.mkdirSync(HOME, { recursive: true });
}

function userAgent() {
  try {
    return fs.readFileSync(UA_FILE, 'utf8').trim() || DESKTOP_UA;
  } catch {
    return DESKTOP_UA;
  }
}

function writeUA(value) {
  ensureHome();
  fs.writeFileSync(UA_FILE, value + '\n', { mode: 0o600 });
}

function readCookieJar() {
  const jar = [];
  if (!fs.existsSync(COOKIE_FILE)) return jar;
  for (const raw of fs.readFileSync(COOKIE_FILE, 'utf8').split(/\r?\n/)) {
    if (!raw || raw.startsWith('# ')) continue;
    const line = raw.startsWith('#HttpOnly_') ? raw.slice('#HttpOnly_'.length) : raw;
    if (line.startsWith('#')) continue;
    const p = line.split('\t');
    if (p.length < 7) continue;
    jar.push({
      domain: p[0], includeSubdomains: p[1] === 'TRUE', path: p[2],
      secure: p[3] === 'TRUE', expires: Number(p[4]) || 0, name: p[5], value: p[6]
    });
  }
  return jar;
}

function cookieHeader() {
  return readCookieJar().map(c => `${c.name}=${c.value}`).join('; ');
}

function cookieValue(name) {
  const c = readCookieJar().find(x => x.name === name);
  return c ? c.value : '';
}

function parseSetCookie(header, fallbackDomain = '.bilibili.com') {
  const [pair, ...attrs] = header.split(';');
  const eq = pair.indexOf('=');
  if (eq < 1) return null;
  const out = {
    domain: fallbackDomain, includeSubdomains: true, path: '/', secure: true,
    expires: 0, name: pair.slice(0, eq).trim(), value: pair.slice(eq + 1)
  };
  for (const attr of attrs) {
    const i = attr.indexOf('=');
    const key = (i === -1 ? attr : attr.slice(0, i)).trim().toLowerCase();
    const val = i === -1 ? '' : attr.slice(i + 1).trim();
    if (key === 'domain' && val) out.domain = val;
    else if (key === 'path' && val) out.path = val;
    else if (key === 'secure') out.secure = true;
    else if (key === 'max-age' && Number(val) > 0) out.expires = Math.floor(Date.now() / 1000) + Number(val);
    else if (key === 'expires' && val) {
      const t = Date.parse(val);
      if (!Number.isNaN(t)) out.expires = Math.floor(t / 1000);
    }
  }
  return out;
}

function mergeCookies(jar, incoming) {
  const map = new Map(jar.map(c => [`${c.domain}\t${c.path}\t${c.name}`, c]));
  for (const c of incoming) {
    if (c && c.name) map.set(`${c.domain}\t${c.path}\t${c.name}`, c);
  }
  return [...map.values()];
}

function writeCookieJar(jar) {
  ensureHome();
  const lines = ['# Netscape HTTP Cookie File', '# Generated by bilibili-web skill', ''];
  for (const c of jar) {
    if (!c.name) continue;
    lines.push([c.domain, c.includeSubdomains ? 'TRUE' : 'FALSE', c.path,
      c.secure ? 'TRUE' : 'FALSE', String(c.expires || 0), c.name, c.value].join('\t'));
  }
  fs.writeFileSync(COOKIE_FILE, lines.join('\n') + '\n', { mode: 0o600 });
  try { fs.chmodSync(COOKIE_FILE, 0o600); } catch {}
}

function saveCookiesFromResponse(res, callbackUrl) {
  let jar = readCookieJar();
  const incoming = [];
  if (typeof res.headers.getSetCookie === 'function') {
    for (const h of res.headers.getSetCookie()) {
      const c = parseSetCookie(h);
      if (c) incoming.push(c);
    }
  }
  // The QR poll response may also carry auth tokens in its callback URL.
  if (callbackUrl) {
    try {
      const u = new URL(callbackUrl);
      for (const name of ['SESSDATA', 'bili_jct', 'DedeUserID', 'DedeUserID__ckMd5', 'sid', 'buvid3', 'buvid4']) {
        const value = u.searchParams.get(name);
        if (value) {
          incoming.push({
            domain: '.bilibili.com', includeSubdomains: true, path: '/',
            secure: true, expires: 0, name, value
          });
        }
      }
    } catch {}
  }
  jar = mergeCookies(jar, incoming);
  writeCookieJar(jar);
  return incoming.length;
}

async function request(url, options = {}) {
  const headers = {
    'User-Agent': userAgent(),
    'Accept': 'application/json, text/plain, */*',
    'Referer': options.referer || 'https://www.bilibili.com/',
    ...(options.headers || {})
  };
  const cookie = cookieHeader();
  if (cookie) headers.Cookie = cookie;
  const res = await fetch(url, {
    method: options.method || 'GET',
    headers,
    body: options.body,
    redirect: options.redirect || 'follow'
  });
  return res;
}

async function json(url, options = {}) {
  const res = await request(url, options);
  const text = await res.text();
  let body;
  try { body = JSON.parse(text); }
  catch { throw new Error(`HTTP ${res.status}: non-JSON response: ${text.slice(0, 160)}`); }
  return { res, body };
}

function signWbi(params, imgKey, subKey) {
  const mixinKey = WBI_TAB.map(i => (imgKey + subKey)[i]).join('').slice(0, 32);
  const wts = Math.floor(Date.now() / 1000);
  const p = { ...params, wts };
  const query = Object.keys(p).sort().map(k => {
    const v = String(p[k]).replace(/[!'()*]/g, c => '%' + c.charCodeAt(0).toString(16));
    return `${encodeURIComponent(k)}=${encodeURIComponent(v)}`;
  }).join('&');
  const w_rid = crypto.createHash('md5').update(query + mixinKey).digest('hex');
  return `${query}&w_rid=${w_rid}`;
}

async function getWbiKeys() {
  const { body } = await json('https://api.bilibili.com/x/web-interface/nav');
  if (!body?.data?.wbi_img) throw new Error('WBI keys unavailable (not logged in?)');
  const imgKey = new URL(body.data.wbi_img.img_url).pathname.split('/').pop().split('.')[0];
  const subKey = new URL(body.data.wbi_img.sub_url).pathname.split('/').pop().split('.')[0];
  return { imgKey, subKey };
}

async function nav() {
  const { body } = await json('https://api.bilibili.com/x/web-interface/nav');
  if (body.code !== 0 || !body.data?.isLogin) {
    throw new Error(`NOT_LOGGED_IN: ${body.code} ${body.message || ''}`.trim());
  }
  return body.data;
}

async function videoInfo(bvid) {
  const { body } = await json(`https://api.bilibili.com/x/web-interface/view?bvid=${encodeURIComponent(bvid)}`,
    { referer: `https://www.bilibili.com/video/${encodeURIComponent(bvid)}` });
  if (body.code !== 0) throw new Error(`video ${bvid}: ${body.code} ${body.message || ''}`);
  return body.data;
}

function requireCsrf() {
  const csrf = cookieValue('bili_jct');
  if (!csrf) throw new Error('缺少 bili_jct cookie，请重新登录');
  return csrf;
}

async function postForm(path, params, referer) {
  const body = new URLSearchParams();
  for (const [key, value] of Object.entries(params)) body.set(key, String(value));
  return json(`https://api.bilibili.com${path}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: body.toString(),
    referer
  });
}

function imageMime(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  if (ext === '.png') return 'image/png';
  if (ext === '.gif') return 'image/gif';
  return 'image/jpeg';
}

async function uploadDynamicImage(filePath) {
  if (!fs.existsSync(filePath)) throw new Error(`image not found: ${filePath}`);
  const ext = path.extname(filePath).toLowerCase();
  if (!['.jpg', '.jpeg', '.png', '.gif'].includes(ext)) {
    throw new Error(`unsupported image format: ${ext || '(no extension)'}`);
  }
  const csrf = requireCsrf();
  const form = new FormData();
  const bytes = fs.readFileSync(filePath);
  form.append('file_up', new Blob([bytes], { type: imageMime(filePath) }), path.basename(filePath));
  form.append('category', 'daily');
  form.append('biz', 'new_dyn');
  form.append('csrf', csrf);
  const res = await request('https://api.bilibili.com/x/dynamic/feed/draw/upload_bfs', {
    method: 'POST',
    body: form,
    referer: 'https://www.bilibili.com/'
  });
  const raw = await res.text();
  let out;
  try { out = JSON.parse(raw); }
  catch { throw new Error(`image upload HTTP ${res.status}: non-JSON response: ${raw.slice(0, 160)}`); }
  if (out.code !== 0 || !out.data?.image_url) {
    throw new Error(`image upload failed: ${out.code} ${out.message || ''}`.trim());
  }
  return {
    img_src: out.data.image_url,
    img_width: Number(out.data.image_width) || 0,
    img_height: Number(out.data.image_height) || 0,
    img_size: Number(out.data.img_size) || 0
  };
}

async function createDynamic(content, images) {
  const csrf = requireCsrf();
  const now = Math.floor(Date.now() / 1000);
  const rand = Math.floor(Math.random() * 10000);
  let mid = 0;
  try { mid = Number((await nav()).mid) || 0; } catch {}
  const dyn_req = {
    content: { contents: [{ raw_text: content || '' }] },
    scene: images.length ? 2 : 1,
    pics: images,
    meta: { app_meta: { from: 'create.dynamic.web', mobi_app: 'web' } },
    upload_id: `${mid || 0}_${now}_${String(rand).padStart(4, '0')}`
  };
  const first = await json(
    `https://api.bilibili.com/x/dynamic/feed/create/dyn?csrf=${encodeURIComponent(csrf)}`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ dyn_req }),
      referer: 'https://www.bilibili.com/'
    }
  );
  if (first.body.code === 0) return { endpoint: 'create/dyn', ...first };
  // Older web endpoint. Keep it as a fallback because some accounts still
  // receive the legacy write path from the web client.
  const body = new URLSearchParams({
    dynamic_id: '0',
    type: '4',
    rid: '0',
    content: content || '',
    up_choose_comment: '0',
    up_close_comment: '0',
    extension: JSON.stringify({ emoji_type: 1, from: { emoji_type: 1 }, flag_cfg: {} }),
    at_uids: '',
    ctrl: '[]',
    csrf_token: csrf,
    csrf
  });
  if (images.length) body.set('pics', JSON.stringify(images));
  const second = await json('https://api.vc.bilibili.com/dynamic_svr/v1/dynamic_svr/create', {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: body.toString(),
    referer: 'https://www.bilibili.com/'
  });
  return { endpoint: 'dynamic_svr/create', ...second, fallbackFrom: first.body };
}

