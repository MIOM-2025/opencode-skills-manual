function parseArgs(argv) {
  const args = [];
  const flags = new Map();
  const takesValue = new Set(['page', 'seconds', 'count', 'folder', 'folder-id', 'progress', 'intro', 'privacy', 'limit', 'images', 'image', 'out', 'root', 'pn', 'ps', 'business', 'title', 'status', 'rpid']);
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const name = a.slice(2);
      flags.set(name, takesValue.has(name) ? argv[++i] : true);
    } else {
      args.push(a);
    }
  }
  return { args, flags };
}

async function cmdLogin(flags) {
  ensureHome();
  writeUA(DESKTOP_UA);
  if (!flags.has('force')) {
    try {
      const n = await nav();
      console.log(JSON.stringify({ alreadyLoggedIn: true, uname: n.uname, mid: n.mid, level: n.level_info?.current_level }));
      console.log('Use `bili login --force` to create a new login link.');
      return;
    } catch {}
  }
  const { body } = await json('https://passport.bilibili.com/x/passport-login/web/qrcode/generate');
  if (body.code !== 0 || !body.data?.url) throw new Error(`login generate failed: ${body.code} ${body.message || ''}`);
  const qr = { url: body.data.url, qrcode_key: body.data.qrcode_key, created: Date.now() };
  fs.writeFileSync(QR_FILE, JSON.stringify(qr, null, 2) + '\n', { mode: 0o600 });
  console.log(JSON.stringify({ loginUrl: qr.url, expiresInSeconds: 180 }));
  console.log('Open this official Bilibili URL on the phone and confirm login, then run: bili poll');
}

async function pollOnce() {
  if (!fs.existsSync(QR_FILE)) throw new Error('no qr.json; run `bili login` first');
  const qr = JSON.parse(fs.readFileSync(QR_FILE, 'utf8'));
  const { res, body } = await json(`https://passport.bilibili.com/x/passport-login/web/qrcode/poll?qrcode_key=${encodeURIComponent(qr.qrcode_key)}`);
  const status = body?.data?.code;
  const result = {
    topCode: body.code, status,
    message: body?.data?.message || body.message || '',
    loggedIn: status === 0
  };
  if (status === 0) {
    const n = saveCookiesFromResponse(res, body.data.url);
    result.savedCookies = n;
    result.cookieNames = readCookieJar().map(c => c.name);
    result.nav = await nav().then(d => ({ uname: d.uname, mid: d.mid, level: d.level_info?.current_level })).catch(() => null);
  }
  return result;
}

async function cmdPoll() {
  const r = await pollOnce();
  console.log(JSON.stringify(r));
  if (r.status === 0) return;
  if (r.status === 86101) process.exitCode = 3;
  else if (r.status === 86090) process.exitCode = 4;
  else if (r.status === 86038) process.exitCode = 5;
  else process.exitCode = 6;
}

async function cmdWait(flags) {
  const seconds = Number(flags.get('seconds') || 180);
  const deadline = Date.now() + Math.max(10, seconds) * 1000;
  let last = null;
  while (Date.now() < deadline) {
    const r = await pollOnce();
    if (r.status !== last) {
      console.log(`[${new Date().toISOString()}] ${r.status} ${r.message}`);
      last = r.status;
    }
    if (r.status === 0) {
      console.log(JSON.stringify({ ok: true, nav: r.nav }));
      return;
    }
    if (r.status === 86038) {
      console.log(JSON.stringify({ ok: false, expired: true }));
      process.exitCode = 5;
      return;
    }
    await new Promise(resolve => setTimeout(resolve, 2000));
  }
  console.log(JSON.stringify({ ok: false, timeout: true, lastStatus: last }));
  process.exitCode = 6;
}

